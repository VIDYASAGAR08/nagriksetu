"""
NagrikSetu AI Engine - Controlled Database Query Tools
Parameterized, authorized query functions executed strictly against the verified SQLite schema.
Never executes arbitrary raw SQL generated by external language models.
"""

import sqlite3
import json
from typing import Dict, Any, List, Optional, Tuple

class DatabaseTools:
    @staticmethod
    def search_schools(
        conn: sqlite3.Connection,
        district: Optional[str] = None,
        query: Optional[str] = None,
        school_type: Optional[str] = None,
        medium: Optional[str] = None,
        limit: int = 5
    ) -> List[Dict[str, Any]]:
        sql = """
            SELECT school_id, school_name, school_type, district, state,
                   address, description, facilities_json, affiliation, recognition
            FROM schools
            WHERE 1=1
        """
        params = []
        if district:
            sql += " AND district LIKE ?"
            params.append(f"%{district}%")
        if query:
            sql += " AND (school_name LIKE ? OR description LIKE ?)"
            params.extend([f"%{query}%", f"%{query}%"])
        if school_type:
            if school_type.lower() == "government":
                sql += " AND (school_name LIKE '%Government%' OR school_name LIKE '%Govt%')"
            elif school_type.lower() == "private":
                sql += " AND (school_name NOT LIKE '%Government%' AND school_name NOT LIKE '%Govt%')"
            else:
                sql += " AND school_type LIKE ?"
                params.append(f"%{school_type}%")

        sql += f" ORDER BY school_id ASC LIMIT {limit}"
        rows = conn.execute(sql, tuple(params)).fetchall()

        results = []
        for r in rows:
            d = dict(r)
            try:
                d["facilities"] = json.loads(d.get("facilities_json") or "[]")
            except Exception:
                d["facilities"] = []
            results.append(d)
        return results

    @staticmethod
    def get_school_profile(conn: sqlite3.Connection, school_id: str) -> Optional[Dict[str, Any]]:
        row = conn.execute("""
            SELECT s.*, 
                   COALESCE(SUM(ps.capacity), 0) AS total_capacity,
                   COALESCE(SUM(ps.current_strength), 0) AS total_enrolled
            FROM schools s
            LEFT JOIN program_sections ps ON ps.institution_id = s.school_id
            WHERE s.school_id = ?
            GROUP BY s.school_id
        """, (school_id.upper(),)).fetchone()
        if not row:
            return None
        res = dict(row)
        progs = conn.execute("""
            SELECT program_name, education_level, degree_type, discipline_or_stream
            FROM academic_programs
            WHERE institution_id = ? AND is_active = 1
            LIMIT 5
        """, (school_id.upper(),)).fetchall()
        res["programs"] = [dict(p) for p in progs]
        return res

    @staticmethod
    def compare_institutions(conn: sqlite3.Connection, id1: str, id2: str) -> Optional[Tuple[Dict[str, Any], Dict[str, Any]]]:
        s1 = DatabaseTools.get_school_profile(conn, id1)
        s2 = DatabaseTools.get_school_profile(conn, id2)
        if s1 and s2:
            return s1, s2
        return None

    @staticmethod
    def get_seat_vacancies_overview(conn: sqlite3.Connection) -> Dict[str, Any]:
        row = conn.execute("""
            SELECT SUM(capacity) AS total_cap, SUM(current_strength) AS total_str, COUNT(*) AS total_sections
            FROM program_sections
        """).fetchone()
        tot_cap = row["total_cap"] or 0
        tot_str = row["total_str"] or 0
        return {
            "total_capacity": tot_cap,
            "total_enrolled": tot_str,
            "open_vacancies": max(0, tot_cap - tot_str),
            "total_sections": row["total_sections"] or 0
        }

    @staticmethod
    def get_student_attendance(conn: sqlite3.Connection, permanent_student_id: str) -> Dict[str, Any]:
        rows = conn.execute("""
            SELECT attendance_date, status, subject_name, remarks
            FROM student_attendance
            WHERE permanent_student_id = ?
            ORDER BY attendance_date DESC
            LIMIT 30
        """, (permanent_student_id,)).fetchall()

        total_days = len(rows)
        present_days = sum(1 for r in rows if r["status"] and r["status"].lower() == "present")
        pct = (present_days / total_days * 100) if total_days > 0 else 0.0

        student = conn.execute("""
            SELECT s.student_name, s.school_id, sc.school_name, s.standard, s.section
            FROM students s
            LEFT JOIN schools sc ON sc.school_id = s.school_id
            WHERE s.permanent_student_id = ?
        """, (permanent_student_id,)).fetchone()

        return {
            "permanent_student_id": permanent_student_id,
            "student_name": student["student_name"] if student else "Student",
            "school_name": student["school_name"] if student else "School",
            "standard": f"{student['standard']}-{student['section']}" if student else "N/A",
            "total_recorded_days": total_days,
            "present_days": present_days,
            "absent_days": total_days - present_days,
            "attendance_percentage": round(pct, 1),
            "recent_records": [dict(r) for r in rows[:5]]
        }

    @staticmethod
    def get_student_results(conn: sqlite3.Connection, permanent_student_id: str) -> Dict[str, Any]:
        rows = conn.execute("""
            SELECT ar.subject_name, ar.exam_name, ar.marks_obtained, ar.maximum_marks, ar.academic_year
            FROM academic_results ar
            JOIN enrollments e ON e.enrollment_id = ar.enrollment_id
            WHERE e.permanent_student_id = ?
            ORDER BY ar.exam_date DESC, ar.subject_name ASC
        """, (permanent_student_id,)).fetchall()

        return {
            "permanent_student_id": permanent_student_id,
            "results": [dict(r) for r in rows]
        }

    @staticmethod
    def get_parent_applications(conn: sqlite3.Connection, parent_user_id: str) -> List[Dict[str, Any]]:
        rows = conn.execute("""
            SELECT a.application_id, a.institution_id, s.school_name, a.applicant_name,
                   a.requested_standard, a.status, a.enrolled_student_id, a.created_at
            FROM admission_applications a
            JOIN schools s ON s.school_id = a.institution_id
            WHERE a.parent_user_id = ?
            ORDER BY a.created_at DESC
        """, (parent_user_id,)).fetchall()
        return [dict(r) for r in rows]

    @staticmethod
    def get_parent_children(conn: sqlite3.Connection, parent_user_id: str) -> List[Dict[str, Any]]:
        guardian = conn.execute("SELECT guardian_id FROM guardians WHERE user_id = ?", (parent_user_id,)).fetchone()
        if not guardian:
            return []
        rows = conn.execute("""
            SELECT s.student_name, s.permanent_student_id, s.school_id, sc.school_name,
                   s.standard, s.section, s.first_language, s.enrollment_status
            FROM student_guardians sg
            JOIN students s ON s.permanent_student_id = sg.permanent_student_id
            LEFT JOIN schools sc ON sc.school_id = s.school_id
            WHERE sg.guardian_id = ? AND sg.is_verified = 1
        """, (guardian["guardian_id"],)).fetchall()
        return [dict(r) for r in rows]

    @staticmethod
    def get_school_admin_desk(conn: sqlite3.Connection, school_id: str) -> Dict[str, Any]:
        row = conn.execute("""
            SELECT
                COUNT(*) as total_apps,
                SUM(CASE WHEN status = 'submitted' THEN 1 ELSE 0 END) as pending_review,
                SUM(CASE WHEN status = 'under_review' THEN 1 ELSE 0 END) as in_review,
                SUM(CASE WHEN status = 'approved' THEN 1 ELSE 0 END) as stage1_approved,
                SUM(CASE WHEN status IN ('stage2_submitted', 'documents_uploaded') THEN 1 ELSE 0 END) as stage2_submitted,
                SUM(CASE WHEN status = 'enrolled' THEN 1 ELSE 0 END) as enrolled
            FROM admission_applications
            WHERE institution_id = ?
        """, (school_id.upper(),)).fetchone()
        return dict(row) if row else {}

    @staticmethod
    def get_section_strengths(conn: sqlite3.Connection, school_id: str) -> List[Dict[str, Any]]:
        rows = conn.execute("""
            SELECT section_id, term_or_year, section_name, capacity, current_strength
            FROM program_sections
            WHERE institution_id = ?
            ORDER BY term_or_year, section_name
            LIMIT 10
        """, (school_id.upper(),)).fetchall()
        return [dict(r) for r in rows]

    @staticmethod
    def get_district_overview(conn: sqlite3.Connection, district: str) -> Dict[str, Any]:
        rows = conn.execute("""
            SELECT school_id, school_name, school_type
            FROM schools
            WHERE district LIKE ?
        """, (f"%{district}%",)).fetchall()
        return {
            "district": district,
            "school_count": len(rows),
            "schools": [dict(r) for r in rows]
        }
